-- Удаляем старое ограничение с битой кодировкой
ALTER TABLE public.models DROP CONSTRAINT IF EXISTS models_category_check;

-- Добавляем корректное ограничение в кодировке UTF-8
-- Мы расширяем список, чтобы он включал все возможные варианты, используемые классификатором и сидингом
ALTER TABLE public.models ADD CONSTRAINT models_category_check 
  CHECK (category IN (
    'Персонаж', 'Аватар', 'NPC', 'Прочее', 'Персонажи', 
    'Архитектура', 'Природа', 'Транспорт', 'Оружие', 
    'Животные', 'Интерьер', 'Мебель', 'Еда', 'Растения'
  ));

COMMENT ON CONSTRAINT models_category_check ON public.models IS 'Список допустимых категорий для моделей (исправленная кодировка)';
